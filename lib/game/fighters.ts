/** One fixed opponent and ruleset per UTC day, the same for every player. */
export function dailyOpponent(date = new Date()): { opponent: OpponentDef; key: string } {
  const key = date.toISOString().slice(0, 10)
  let hash = 0
  for (const ch of key) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0
  const base = CAREER[2 + (hash % (CAREER.length - 2))]
  const bpmShift = (hash >> 4) % 3 === 0 ? 6 : (hash >> 4) % 3 === 1 ? 0 : -4
  return {
    key,
    opponent: {
      ...base,
      id: `daily_${key}`,
      title: "Daily Knockout",
      bpm: base.bpm + bpmShift,
      difficulty: Math.min(0.9, base.difficulty + 0.08),
    },
  }
}
