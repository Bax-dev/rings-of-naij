export type Genre = "afrobeats" | "streethop" | "fuji" | "amapiano" | "highlife"

export type Unlock =
  | { type: "free" }
  | { type: "career"; stage: number }
  | { type: "purchase"; productId: string }

export interface FighterDef {
  id: string
  name: string
  style: string
  strength: string
  weakness: string
  portrait: string
  genre: Genre
  colors: { gloves: string; trunks: string; skin: string; accent: string }
  /** Damage multiplier on every punch. */
  power: number
  /** Minimum ms between punches. */
  punchCooldown: number
  /** How long a dodge protects you, in ms. */
  dodgeMs: number
  /** Vibe gained per on-beat punch is multiplied by this. */
  vibeRate: number
  maxHp: number
  /** Damage taken multiplier (higher = glass jaw). */
  chin: number
  /** Bonus damage multiplier for punches right after a perfect dodge. */
  counterBonus: number
  signature: { name: string; damage: number }
  unlock: Unlock
}

